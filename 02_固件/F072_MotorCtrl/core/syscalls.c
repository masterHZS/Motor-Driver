#include <errno.h>
#include <stddef.h>
#include <sys/stat.h>

/******************************************************************************/
/* Global variable definitions (declared in linker script)                    */
/******************************************************************************/
extern char _ebss;         /* end of .bss  -> heap start (defined in .ld) */
extern char __heap_limit;  /* heap end (defined in .ld)                  */

static char *s_heap_end = (char *)0;

/**
 ******************************************************************************
 ** \brief  堆指针调整 (malloc/free 使用)
 **
 ** \param  [in] incr  需要调整的字节数
 ** \retval 调整前的堆指针, 失败返回 -1
 ******************************************************************************/
void *_sbrk(ptrdiff_t incr)
{
    char *prev_heap_end;

    if ((char *)0 == s_heap_end)
    {
        s_heap_end = &_ebss;
    }
    prev_heap_end = s_heap_end;

    if ((s_heap_end + incr) > &__heap_limit)
    {
        errno = ENOMEM;
        return (void *) -1;
    }

    s_heap_end += incr;
    return (void *) prev_heap_end;
}

